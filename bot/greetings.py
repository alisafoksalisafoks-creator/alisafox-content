def text(name, day: date, chat_id=0):
    """Одна и та же фраза за день и чат, на следующий день — другая."""
    rnd = random.Random(f"{day}:{chat_id}")
    hello = rnd.choice(HELLO)
    head = f"{name}! {hello}!" if name else f"{hello}!"
    return f"{head} {rnd.choice(REPORT)}\n{rnd.choice(COMPLIMENT)} {rnd.choice(WISH)} 🦊"
